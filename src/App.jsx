        const baseMaps = buildConstraintMaps(preservedSchedules, unavailabilities, classroomUnavailabilities, fixedSchedules);
        const loadKeys = new Set(teachingLoads.map(getTeachingLoadKey));
        const fixedByLoad = new Map();
