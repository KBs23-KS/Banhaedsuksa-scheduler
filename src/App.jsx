  unavail.forEach(u => { if (tPlacement[`${u.teacherId}_${u.day}_${u.periodId}`]) health.unavailConflicts.push(`ครู ${teacherMap.get(u.teacherId)?.name || u.teacherId} ถูกจัดในเวลาไม่สะดวก (วัน${u.day} คาบ ${u.periodId})`); });
