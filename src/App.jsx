  fixed.forEach(f => checkPlacement(f, true));

  Object.entries(tPlacement).filter(([_, arr]) => arr.length > 1).forEach(([_, arr]) => health.teacherConflicts.push(`ครู ${teacherMap.get(arr[0].teacherId)?.name || arr[0].teacherId} ซ้อนทับ ${arr.length} วิชา (วัน${arr[0].day} คาบ ${arr[0].periodId})`));
